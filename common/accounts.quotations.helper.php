This area allows you to manage all the quotations that have been generated in your account.<br /><br />

You will be able to view details such as the quotation number, the amount, the date when the quotation was generated, the due date for the quotation among many more other details.<br  /><br  />

{Msgs::Info('A <b class="rt-strong rt-tone-royal">Quotation (aka Proforma Invoice or Quote)</b> is a document that  a supplier submits to a potential client with a proposed price for the goods and/or services based on certain conditions stipulated by the client.')}

<div align="center"><b class="rt-strong rt-tone-cardinal">MORE INFORMATION</b></div><br />
View more details such as the quotation items as well as other useful buttons by clicking on <strong>More...</strong> next to the quotation number.</div><br />
The buttons are explained below:<br /><br />

<button class="btn-xs tooltips btn-success none"><i class="fas fa-share"></i> Convert To Invoice </button> will prompt you if you would like to convert the quotation into an invoice. Upon your confirmation, the invoice will be generated and you will be redirected to the invoice page.<br  /><br  />

<button class="btn-xs tooltips btn-info none"><i class="fas fa-envelope"></i> Resend </button> will prompt you if you would like to send the quotation to the email address. If you agree, the quotation will be emailed.<br  /><br  />

<strong>NOTE</strong>: You can also be able to open and view the respective quotation by clicking on the invoice number itself which will be opened in a new tab.<br  /><br  />

