<strong>What is a mobile number?</strong><br /><br />
  A mobile number is a sequence of digits assigned to a wireless electronic telephone device, such as a mobile telephone, or to other devices for data transmission via the public switched telephone network (PSTN) or other public and private networks.<br /><br />
  <strong>Why should you have  your mobile number approved?</strong><br /><br />
  JPesa may allow you to make deposits and/or withdraws upto a certain limit and thereafter will require that you approve your mobile number.
<br /><br />The number that you attach will help JPesa to identify you as its customer but also will be validated to make sure that it complies with relevant regulations.<br /><br />

  <strong>How do you add a mobile number?</strong><br />
  <br />
  JPesa gives you the flexibility of adding as many numbers as you want as long as they are registered within your the same names that are on the account. <br  /><br />
  To add a mobile number;
  <ul>
    <li>Navigate and click on the <strong>Add</strong> button.</li>
    <li>Enter the details of the mobile number and some comments</li>
    <li>Click on Save &amp; Send Pin </li>
  </ul>
A PIN will then be sent to your handset which you can then enter back into your account and once it is validated, your phone will be confirmed and wait for approval.
