<h3>What is CVV2 Security Code?</h3>

<p>Card Verification Value, CVV or CVV2, is an authentication system established by credit card companies to further efforts toward reducing fraud for internet transactions. The card holder is required to enter the CVV2 number in at transaction time to verify that the card is on hand.<br />


<h4>Visa &amp; MasterCard</h4>

<img src="templates/common/media/images/cvv2.png" /><br /><br />
The CVV2 is printed on your Visa card or MasterCard in the signature area on the back of the card. It is the last 3 digits AFTER the credit card number in the signature area of the card.<br />
<br />
<h4>American Express</h4>
American Express cards have a 4-digit security code located on the front-right corner of the card.
