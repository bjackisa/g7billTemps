[[CNS]] Commerce Platform for Business<br />
<br />
[[CNS]] Commerce Platform is a full-stack payment processing solution that helps you accept and make payments globally.<br />
<br />
To offer a more comprehensive platform, we publish an API Mode model which provides a real-time interface with our systems.<br />
<br />
The API is a white-label solution that enables you to integrate the API application with your system so you can brand and sale our services directly from your system.<br />
<br />
<strong>Accept payments</strong><br />
<br />
Accept payments from customers all over the world. Give your customers flexibility to pay the way they want, including:
<ul>
  <li>[[CNS]] exclusives, like [[CNS]] Credit. </li>
  <li>Debit or credit cards, like Visa, Mastercard, and American Express. </li>
  <li>Alternative payment methods, like EFT, RTGS, and more.<br />
  </li>
</ul>
<strong>Make payments</strong><br />
<br />
Make payments to multiple recipients at once. Send payouts in different currencies than your [[CNS]] balance.
