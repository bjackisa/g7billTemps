<strong>What is an API?</strong><br /><br />
  Technically, API stands for Application Programming Interface. You can also say that  an API is  the part of the server that receives requests and sends responses.<br /><br />
  <strong>How does it work?</strong><br />
 <p align="center"><img src="{$api}" alt="API" {U::iSize(['i'=>$api,'t'=>240])} /></p>
 As illustrated above an API acts as a channel through which requests can be made and responses obtained in order to achieve a certain purpose.<br /><br /> An API thus hides the complexity from developers while extending systems to partners, helps in organizing code, and makes components reusable<br /><br />
  <strong>What is an Access Key?</strong><br /><br />
  An Access Key is a unique identifier used to authenticate or authorize a user, developer, or calling program to an API.<br /><br />
  This Access Key can be generated by editing and then setting the status of the API to Enabled. <br /><br />
  <strong>What is an IPN?</strong><br /><br />
  IPN stands for Instant Payment Notification which is a message service that automatically notifies you of events related to [[CN]] transactions. <br /><br />
  You can use it to automate back-office and administrative functions, including automatically fulfilling orders and providing customers with order status. <br />
