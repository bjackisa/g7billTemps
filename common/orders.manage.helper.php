In this area you can be able to manage the Orders you create in your account.<br /><br />

Here you you will be able to view details about your orders such as ownerID, Package ordered for, the date when it expires, its status among many more other details.<br /><br />

There are various statuses that you might be able to see in your account and below, we have listed the most common that you will find.<br />
<br />

<div align="center"><b class="rt-strong rt-tone-royal">STATUSES</b></div>
<ul>
<li><b class="badge badge-success">Active</b> -This is an actively running order </li>
<li><b class="badge badge-danger">Cancelled</b> - This is when an order has been cancelled either by the customer or the system for various reasons such as having exceeded the expiry date among others</li>
<li><b class="badge badge-warning">Pending</b> - This is the first status that an order takes on after it has just been created by the customer until it is actioned by the merchant</li>
<li><b class="badge badge-danger">Suspended</b> - This is when an  order is deactivated by the merchant for various reasons such as being overdue among others</li>
<li> <b class="badge badge-success">Completed</b> - This is when an order has been shipped/picked up, and receipt is confirmed.</li>
<li><b class="badge badge-primary">Ended</b> - This refers to an order whose service/product has been used up</li>
<li> <b class="badge badge-metal">Refunded</b> - This is when payment is refunded to the customer for their order</li>
<li><b class="badge badge-danger">Denied</b> - This is when an order is declined by the merchant for various reasons</li>
<li> <b class="badge badge-primary">Confirmed</b> - This is an order that has been confirmed  by the merchant for delivery</li>
<li><b class="badge badge-success">Shipped</b> - This is when a client's order has been dispatched and it can be picked up by them</li>
<li> <b class="badge badge-warning">Processing</b> - This is when payment / confirmation for an order is received &amp; the order is accepted, but it is awaiting fulfillment.</li>
<li> <b class="badge badge-primary">Submitted</b> - This is when a client's order has been submitted to the merchant successfully</li>
<li> <b class="badge badge-success">Approved</b> - This is when a client's order has been approved</li>
<li> <b class="badge badge-danger">Incomplete</b> - This is when a client's order is incomplete for various reasons such insufficient information to mention but a few</li>
<li> <b class="badge badge-danger">Failed</b> - This is when an order did not come through for various reasons</li>
<li> <b class="badge badge-danger">Failed Approval</b> - This is when a client's order failed to be approved</li>
<li><b class="badge badge-primary">No Pending Action</b> - In this case, there is no action that is pending to be done</li>
<li> <b class="badge badge-warning">Pending Customer Action</b> - This means that an order was placed successfully and responded to by the merchant but it is still awaiting customer action</li>
<li> <b class="badge badge-warning">Pending Customer Return</b> - This is when an order is about to be returned by the customer for some reasons</li>
<li> <b class="badge badge-warning">Pending Merchant Action</b> - This is the status that will be shown awaiting for confirmation from the merchant</li>
<li> <b class="badge badge-warning">Pending Approval</b> - This is the status that will be shown shortly before the order is approved should the client want to change their mind for any reasons.</li>
<li> <b class="badge badge-warning">Pending Remove</b> - This is the status that will be shown shortly before the order is removed should the client want to change their mind for any reasons.</li>
<li> <b class="badge badge-success">Quoted</b> - These are orders that were generated through quotations or those with quotations</li>
<li> <b class="badge badge-danger">Removed</b> - This may result when a customer does not make the payment within the stipulated time limit and their order is removed from the system.<br /><br />
</li>
</ul>

