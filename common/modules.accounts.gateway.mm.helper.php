This area presents information to help you in the process of making your payment through mobile money.<br /><br />
<b class="rt-strong rt-tone-cardinal">HOW TO COMPLETE THE PAYMENT</b><br /><br />
<ul>
<li>Enter your mobile phone number from which the funds will be deducted.</li>
<li>Shortly after, the system will initiate the payment on your handset with a popup window prompting you to enter your PIN number.</li>
<li>Upon entering the correct PIN, the system will deduct funds off your mobile money account.</li>
<li>The deducted funds will then be received onto your <strong>[[CN]]</strong> account.</li>
<li>Once the payment has been confirmed and approved, your product/service will be activated.</li>
</ul><br />

{Msgs::Info('Ensure that you have enough funds including charges on your mobile money account otherwise you will not receive the popup window on your handset.')}

<div align="center"><b class="rt-strong">MORE INFORMATION</b></div><br />
The information provided includes invoice details, transaction information, mobile money payments among others which are explained in detail below.<br /><br />

<strong>Invoice Details:</strong> This information is specific to the invoice details and includes information such as amount due which is the expected amount to be paid, invoice number that helps to trace the specific invoice, order IP that shows the IP address from which the invoice was generated to mention but a few.<br /><br />
<strong>Transaction Information:</strong> This information is about the transaction that is being made and it includes the order number, transaction ID, payment mode which in this case would be mobile money among others.<br /><br />
<strong>Mobile Money Payments:</strong> This is where the mobile number to be charged is added as well as an explanation about the format in which it is to be entered. <br /><br />

<strong>NOTE</strong>: It is also possible to open and view the respective invoice should you like to do so by clicking on the invoice number which is given in the invoice details and it will be opened in a new tab.<br  /><br  />

