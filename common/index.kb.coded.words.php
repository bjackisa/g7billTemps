<strong>What are coded words?</strong><br />
    G7Bill has a system of letters which are are combined together to represent other words or phrases.
  <br /><br />
  <strong>Why should you use coded words? </strong><br />
    The coded words are used to help you when you need to make changes to some important information throughour your pages. With the coded words, it is much easier to do updating in the sense that you only have to update once and the changes will take effect wherever that change is needed. <br /><br />
    Take for example, you have your company email address or telephone number defined throughout your webpages, if you write them directly, you have to look for wherever they appear and  change them manually. <br /><br />
    When you are using coded words on the other hand, you only have to update once and your changes take effect immediately wherever the codes are found. <br /><br />
<strong>How can you use the coded words?  </strong><br />
You  can be able to use the following coded words by putting the letters below within two square brackets [[]] and then the returned value will be what is configured in the system  corresponding to the letters; If you for instance put CN in two square brackets, the company name will be returned. For example using CN within the square brackets, returns the company of the website using this website as  [[CN]]<br /><br />
<strong>List of coded words used</strong><br />
    <strong>CE</strong>  => Company Email <br />
    <strong>CN</strong>  => Company Name <br />
    <strong>CU</strong>  => Company URL <br />
    <strong>UAN</strong> => User Account Number<br />
    <strong>UN</strong>  => User Name <br />
    
