<strong>What is a bank account?</strong><br /><br />
A bank account is a financial account maintained by a bank or other financial institution in which the financial transactions between the bank and a customer are recorded.<br /><br />
  <strong>Why should you have  your bank account?</strong><br />
  <br />
  JPesa gives you the opportunity to withdraw as well as deposit from your bank account. may allow you to make deposits and/or withdraws upto a certain limit and thereafter will require that you approve your bank account.
<br />
<br />The number that you attach will help JPesa to identify you as its customer but also will be validated to make sure that it complies with relevant regulations.<br /><br />

