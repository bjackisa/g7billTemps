<p><strong>The Account Profile</strong></p>
<p>The Account Profile page provides you with visibility of your basic account information.  An account can include an entire company or an individual user, depending on the size of your account.</p>
<p>Depending on your role and subscription plan, you can also view and manage advanced features, such as account support information, associated credit cards, the account's API settings, and so much more details.</p>
The Profile page lets you modify information associated with your account. You can modify the following information:
<ul>
  <li>Personal information such as birthday and marital status</li>
  <li>Phone numbers</li>
  <li>Address, city and zip</li>
  <li>Legal identification</li>
  <li>Tax Identification Number</li>
  <li>Regulatory information</li>
  <li>Billing currency, income and source of income</li>
  <li>And much more ...</li>
</ul>
<p><strong>Change your profile picture</strong></p>
<p>You can choose a photo to set as your [[CN]] profile picture. Your profile picture is the same as your [[CN]] Account picture.</p>
