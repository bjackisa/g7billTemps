  <p>In this area you can manage the blacklists associated with your email addresses.</p>
  <p class="rt-strong">What Is Blacklist</p>
  <p>A blacklist is a list of email addresses or domains that are prevented from sending messages to email users. When an email address is added to this list, any messages that are sent by it will be disregarded. </p>
  <p>The email will not be delivered to the inbox and it will be deleted. In some cases, the email is bounced back to the sender and the sender is given a message that the email was not delivered.</p>
  <p class="rt-strong">Purpose of Blacklist</p>
  <p>The purpose of a blacklist is to cut down on the amount of spam that runs rampant on the Internet. Many product sellers use spam as a way to market their products to very large numbers of people.</p>
  <p>For example, they will get large databases of millions of email addresses and then send out a mass message to all of them. If they can even get a small percentage of sales off this list, it can be very lucrative. The blacklisting process aims to protect consumers from these mass email blasts.</p>
