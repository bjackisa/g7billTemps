Shares are units of equity ownership in a corporation.<br /><br />
For some companies, shares exist as a financial asset providing for an equal distribution of any residual profits, if any are declared, in the form of dividends. Shareholders of a stock that pays no dividends do not participate in a distribution of profits.<br /><br />
In this area you can be able to manage the Shares you own in your account.<br /><br />
Here you you will be able to view details about your Shares such as the units, current value, its status among many more other details.<br /><br />

