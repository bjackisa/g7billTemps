  <strong>What kind of documents can you submit to [[CN]]?</strong> <br /><br />
  <span id="1"><strong><u>INDIVIDUALS</u></strong></span><br /><br />
The following documents are required to be submitted by the applicant in the process of creating an account for  individuals<br /><br />
  <ol>
	<li>Identification Documents (Acceptable IDs)</li>
    <ul>
      <li>National IDs, Passports, Employment ID, Driver’s License and NSSF Card. <strong>Preferred ID ➢ National ID</strong></li>
   	  <li>Passports are the ONLY acceptable form of identification proof for foreign nationals and Work Permit/Certificate of residence</li>
   	  <li> FATCA form for US Nationals   	    </li>
   	  <li>Refugees: Refugee ID
   	    Minors:
   	    The minor’s information, birth certificate/Health cards and photos must be obtained. While the minor’s Guardian who will operate the account MUST provide Individual requirements</li>
   	  <li>Students:
   	    National ID/Student ID </li>
    </ul>
    <li>Proof of residence/ address verification include any of the following
      <ul>
        <li>Letter from a public authority or embassy or consular office</li>
        <li>Utility Bills in the customer’s name and not older than 3 months</li>
        <li> Where utility bill is not in the name of the customer obtain a copy of the tenancy agreement</li>
        <li> Letter of recommendation from employer</li>
        <li> LC Letter confirming residence</li>
        <li> Letter from School/ University administration in case of students</li>
        <li> Bank statement from existing or previous bank bearing the current customer’s address.</li>
        <li> Certificate of residence for foreigners</li>
      </ul>
    </li>
       <li>Proof of Income/Source of Income
      <ul>
        <li>Letter of recommendation/appointment/confirmation from employer</li>
        <li>Payslip not older than 3 months<br />
        </li>
        <li>Declaration of Income form<br />
        </li>
        <li>Trading License<br />
        </li>
        <li>Work Permit (only applicable to Foreign Nationals)<br />
        </li>
        <li>Financial statements for a company older than a year<br />
        </li>
        <li>Memorandum/Articles of association for a company that has been in existence for less than a year</li>
      </ul>
    </li>
  </ol>
