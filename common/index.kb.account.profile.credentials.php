    <strong><span id="1">How to fix common issues that can affect the password reset process</span></strong>
    
    <strong><span id="2">I can't find the password reset email in my inbox</span></strong><br /><br />
    If you have asked the system for a password reset and after a couple of minutes you still haven't received the password reset email:</p>
  </p>
  <ul>
    <li>Please ensure to check your spam/junk folders in case the email has been filtered out.</li>
    <li>Some email software sends filtered emails to their "deleted folder" or "waste bin" even though they also have a spam folder, so make sure to check there as well.</li>
    <li>If you do find the email in any of these folders, please make sure to whitelist our email address.</li>
</ul> 

<strong><span id="2">The password reset email isn't arriving and I already checked my junk/deleted folder</span></strong><br /><br />
If you have asked the system for a password reset and after a couple of minutes you don't have the email in inbox nor in junk/spam/deleted folders:<br /><br />
  <ul>
    <li>It might be better to wait at least 5 or 10 minutes rather than try requesting another password reset right away. This is in case your email provider is experiencing a delay in processing the email our system sent.</li>
    <li>If you do decide to try requesting a new password reset email without having received the first one, please keep in mind that you might first receive the previous password reset email. In this case, the first email will have an expired password, because the reset passwords expire as soon as a new password reset is requested. Make sure to always use the absolute last password reset email you have received.</li>
</ul> 
<strong>HOW OFTEN SHOULD I CHANGE MY PASSWORD?</strong><br /><br />
  We recommend you change your password and security questions from time to time. There are a few cases where it's a good precaution, for example:</p>
  <ul>
    <li>    You notice something suspicious on your [[CNS]] account</li>
    <li>You suspect that someone you don't trust has your password</li>
    <li> You notice something suspicious in your email account or other online accounts</li>
    <li> You have recently removed malware from your system</li>
    <li>[[CNS]] asks you to change your password</li>
  </ul>
  <p>If one of these occurs, change your Password, PIN, and security questions immediately. You can change these under <a href="welcome.php?dad=account&jc=profile&hs=credentials" target="_blank" rel="nofollow noopener noreferrer" class="ignore">personal settings</a>.<br />
    <br />
  If you receive an email asking you to change your password, it could be a case of phishing. Instead of clicking on a suspect link in an email, just log into your [[CNS]] account by manually typing the URL. Click the Settings tab, and then Personal Info. You will find the password, security questions, and PIN (if you've set one up) on this page.</p>
