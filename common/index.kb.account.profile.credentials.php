There are two ways through which you can be able to trigger a password reset through the system. You can either do so before logging in to your [[CN]] account by using the <a href="#1"> reset password feature</a> on the login page or if you are already logged in to [[CN]] account, you can use the <a href="#2" target="_blank" rel="nofollow noopener noreferrer">change password</a> feature. <br /><br /> 

Either way, your password will be changed and in this article we will be explaining the two ways to have it changed.<br /><br />

<strong>TIPS FOR CREATING A SECURE PASSWORD</strong><br /><br />
Having a secure, unique password for each of your online accounts is critically important. If a scammer gets just one password, they can begin to access your other accounts. That’s why it’s important to have a strong, unique password for your [[CN]] login.<br />
<br />
A strong password should have the following characteristics:<br /><br />
  <ul>
    <li>More than 8 characters long</li>
    <li>Use lower case, upper case, a number, and a special character [like ~!@#$%^&amp;*()_+=?&gt;&lt;.,/]</li>
    <li>Not a word or date associated with you (like a pet's name, family names, or birth dates)</li>
    <li>Use a password that you'll be using only for your [[CN]] account</li>
    <li>A combination of words with unusual capitalization, numbers, and special characters interspersed. Misspelled words are stronger because they are not in the dictionary used by attackers.</li>
    <li>Keep your password secret. We'll never ask for your password by email, instant message or phone</li>
    <li>Something you can remember</li>
  </ul> 
  The following are the ways through which you can be able to have your password changed through the system by using the feature to:<br /><br />
