<strong>What is a digital wallet?</strong><br /><br />
Digital wallets offer a convenient way to pay by allowing you to simply use your phone to pay instead of cash or your plastic credit card.
<br />
<br />The wallet feature lets people pay with a [[CN]] account, a credit or debit card, bank account or a line of credit limit that can be applied for within the app. Like Google Wallet, the new [[CN]] app incorporates deals and discounts that are then automatically applied when you pay.
