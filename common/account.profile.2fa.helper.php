<p><strong>What Is Two-Factor Authentication (2FA)?</strong><br />
  <br />
  Two-factor authentication is a security feature that is used by most of the major sites like Facebook, Apple, Google as it provides an additional security layer for the site. <br />
  <br />
  A single-factor authentication (SFA) is simply an authentication option in which the user provides only one factor, a password. <br />
  <br />
  Whereas in two-factor authentication, just a password is not enough and the authentication depends on two factors. The first factor is the password whereas the second factor can be some key or security code. So, both components are necessary for authentication.<br />
  <br />
  <strong>About Google Authenticator</strong> <br />
  Google Authenticator is a free app, that you can download from App Store/Play Store, that provides a random 6-digit code once you scan it from the QR Code. And after every 30 seconds, the code updates.<br />
