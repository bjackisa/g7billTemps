<p>We provide you with access to a lot of sensitive and important data. Keeping this data and all of your accounts safe is a priority.</p>
<p>One security tip often given to users is to regularly change passwords. According to Thytoctic, 80% of all cyber security attacks involve a weak or stolen password. Changing your password regularly reduces your risk of exposure and avoids a number of dangers.</p>

{FF::Line('Benefits of Changing Your Password Regularly')}

<p><strong>1.</strong> Limits breaches to multiple accounts
Reusing your [[CN]] password, increases risk of access to several accounts if your password is hacked. Change your password to something unique for each of your accounts. For example, do not use your Facebook password for your  account.</p>

<p><strong>2.</strong> Prevents constant access
A hacker may try to access your account more than once over a period of time. Changing your password reduces the risk that they will have frequent access.</p>

<p><strong>3.</strong> Prevents use of saved passwords
If you lose or change computers, it is possible someone may gain access to your saved passwords. Consistently changing your password means that even if someone finds an old, saved password, it will no longer be useful<strong>.</strong></p>

<p><strong>4</strong>. Limits access gained by keystroke loggers
A keystroke logger is surveillance technology used to record keystrokes. It is often used to steal login credentials. Regularly changing your password makes it less likely that passwords obtained this way will be useful for any length of time.</p>

Credential stealing is more and more common, and is prevalent throughout the world. Help keep your credentials safe by changing your password on a regular basis.
