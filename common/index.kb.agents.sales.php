<p><strong>Who are  Sales Agents?</strong></p>
<p>Sales Agents are also known as Securities and Commodities Sales Agents and they basically do business on behalf of individuals, businesses and or organizations with authorization. Their job is to basically buy and sell securities in   investment and trading firms and develop and implement financial plans   for individuals, businesses, and organizations. </p>
<p><strong>What do Sales Agents do?</strong></p>
<p>Sales Agents  keep accurate   records of transactions by reviewing all security transactions to ensure accuracy of information and conformance to governing agency regulations. </p>
<p><strong>They do also carry out the following tasks:</strong></p>
<ul>
  <li>Complete sales orders and submit them for processing of client-requested transactions.</li>
  <li>Contact prospective customers to determine customer needs, present information, or explain available services.</li>
  <li>Interview clients to determine clients&rsquo; assets, liabilities, cash flow, insurance coverage, tax status, or financial objectives.</li>
  <li>Discuss financial options with clients and keep them informed about transactions.</li>
  <li>Develop financial plans, based on analysis of clients&rsquo; financial status.</li>
  <li>Analyze market conditions to determine optimum times to execute securities transactions.</li>
  <li>Review   financial periodicals, stock and bond reports, business publications,   or other material to identify potential investments for clients or to   keep abreast of trends affecting market conditions.</li>
  <li>Inform and advise concerned parties regarding fluctuations or securities transactions affecting plans or accounts.</li>
</ul>
